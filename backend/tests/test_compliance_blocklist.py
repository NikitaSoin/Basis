"""Комплаенс-фильтр ловит СОВЕТ купить/продать бумаги, а не само слово (владелец 2026-09-13).

Прецедент: черновик институтов был отклонён целиком за фразу о вынужденной продаже
активов — описательное «продать» попало под голое `\\bпродать\\b`.
"""
from app.services.situation_overlay import _BLOCKLIST
from app.services import overview_synthesis as ov, stress_interpreter as si

ALLOWED = [
    "компании вынуждены продать активы под давлением санкций",
    "нерезиденты продают бумаги через дружественные юрисдикции",
    "рекомендации Банка России по ограничению рисков",
    "совет директоров рекомендовал дивиденд 12 руб.",
    "обязательная продажа валютной выручки отменена",
    "вынужденная продажа доли иностранным инвестором",
    "купля-продажа земли иностранцами ограничена",
]
BLOCKED = [
    "стоит купить акции на снижении",
    "рекомендуем продать облигации до заседания",
    "продать акции Сбербанка сейчас",
    "пора покупать бумаги экспортёров",
    "рекомендация: держать акции до отсечки",
    "наша рекомендация — покупать",
    "инвестидея: докупить на просадке",
]


def test_описательные_формулировки_проходят():
    for s in ALLOWED:
        assert not _BLOCKLIST.search(s), s


def test_совет_купить_продать_блокируется():
    for s in BLOCKED:
        assert _BLOCKLIST.search(s), s


def test_топонимы_и_оккупация_по_прежнему_блокируются():
    for s in ("территория оккупирована", "город Бахмут", "аннексированные регионы"):
        assert _BLOCKLIST.search(s), s


def test_маски_карточек_согласованы():
    for rx in (ov._BANNED, si._BANNED):
        assert not rx.search("компания вынуждена продать актив по требованию регулятора")
        assert not rx.search("совет директоров рекомендовал дивиденд")
        assert rx.search("Рекомендуем покупать на снижении.")
        assert rx.search("стоит купить акции")
        assert rx.search("целевая цена 350 руб.")
