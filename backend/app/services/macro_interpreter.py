    by_key = {(i.get("code"), i.get("metric")): i for i in indicators}
    out: dict = {}
    for code, metric, label in _KEY_FACT_SPECS:
        ind = by_key.get((code, metric))
        if not ind or ind.get("current_value") is None:
            continue
        unit = ind.get("unit") or ""
        # Единицы человеческим языком и здесь: выпуск читает человек, а «4.36 usd/bbl»
        # он читает как ошибку вёрстки (владелец, 2026-08-09).
        from app.services.macro_units import fmt as _fmt_unit
        val = _fmt_unit(ind["current_value"], unit)
        # 🔴 Для КВАРТАЛЬНЫХ рядов пишем период словами. Ряд ведётся по конвенции FRED
        # (дата = НАЧАЛО квартала), и «2026-04-01» модель прочитала как «I квартал»,
        # хотя это второй: в выпуске появилось «ВВП I кв. +0,9%» при том, что первый
        # квартал был −0,2%. Дата начала периода — не название периода.
        period = _period_label(ind)
        parts = [f"{val} ({period})"]
        if code == "budget_balance_ytd" and isinstance(ind.get("current_value"), (int, float)):
            # Дефицит в % годового ВВП — так его называют ЦБ, Минфин и пресса, и
            # именно в этом виде он сопоставим между годами.
            pct = float(ind["current_value"]) / _GDP_NOMINAL_RUB_BLN * 100
            parts.append(f"это {pct:.1f}% годового ВВП ({_GDP_NOMINAL_NOTE})")
        if ind.get("direction_vs_previous_point"):
            parts.append(ind["direction_vs_previous_point"])
        out[label] = ", ".join(parts)

    # 🔴 Внешние ожидания подмешиваем ПРЯМО СЮДА (2026-08-08, вторая итерация).
    # Отдельным блоком снапшота — даже поднятым на второе место — модель их не
    # использовала: писала «рекордный обвал инвестиций», имея под рукой прогнозы
    # Минэка и РСПП о −1,5% за год. key_facts — тот блок, из которого промпт велит
    # брать формулировки о текущем состоянии, и туда модель смотрит всегда.
    for block in (expectations or []):
        claims = [str(x.get("claim_from_source") or "")[:200]
                  for x in (block.get("external_sources_not_our_data") or [])[:2]]
        if not claims:
            continue
        out[f"{block.get('indicator')} — как это соотносится с ожиданиями"] = (
            f"наше значение {block.get('our_value')} против обычных "
            f"{block.get('median_previous')} по ряду; внешние прогнозы и разборы: "
            + " || ".join(claims)
            + " — упоминаешь показатель, обязательно скажи, ожидалось ли движение "
              "и кем (это ЧУЖИЕ оценки, приводи с автором)")
    return out


