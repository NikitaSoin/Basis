def gather_articles(db: Session, scope: str, window_days: int = _WINDOW_DAYS) -> list[dict]:
    """Лента очага за широкое окно. В отличие от барометра берём длинный пересказ:
    из обрезки в 500 символов не видно ни целей сторон, ни ограничений."""
    cutoff = date.today() - timedelta(days=window_days)
    rows = (db.query(GeoDigestArticle)
            .filter(GeoDigestArticle.target == scope,
                    GeoDigestArticle.published_at >= cutoff)
            .order_by(GeoDigestArticle.published_at.desc())
            .limit(_MAX_PER_SCOPE).all())
    return [{
        "date": r.published_at.isoformat() if r.published_at else None,
        "title": r.title,
        "summary": (r.summary or "")[:_SUMMARY_CHARS],
    } for r in rows]


