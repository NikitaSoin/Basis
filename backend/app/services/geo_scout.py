"""Фаза РАЗВЕДКИ гео-выпуска: собрать материал и записать досье — до текста.

🔴 ПОСТАНОВКА ВЛАДЕЛЬЦА (2026-08-12), которой этот модуль реализует недостающую
половину: «агенту нужно дать функционал — он должен уметь ходить в веб-поиск,
заходить на сайты, собирать оттуда информацию, скачивать файлы и доставать нужное,
если в ходе анализа ему не хватило материала. Дальше агент, после того как всё
собрал и проанализировал, всё это отдельно записал, а потом по логике системного
промпта написал на сайте анализ».

Как было до этого: барометр собирался ОДНИМ вызовом модели. На вход — лента и
вчерашний выпуск, на выход — готовый JSON витрины. Если в ленте не хватало
материала, добрать было нечем: модель либо честно писала «данных нет», либо
заполняла пробел общими словами, и отличить одно от другого постфактум было
нельзя — промежуточного слоя не существовало.

Как стало: два раздельных прохода.
  1. РАЗВЕДКА (здесь). Агент с инструментами: полка методичек, веб-поиск,
     открытие документов, внутренняя хроника. Задача — не писать витрину, а
     СОБРАТЬ: что произошло, чем подтверждается, чего не хватает. Результат —
     досье, которое сохраняется ОТДЕЛЬНОЙ версией и живёт независимо от текста.
  2. ПИСЬМО (barometer_daily). Системный промпт задаёт структуру выхода, досье
     идёт на вход как собранный материал.

🔴 ЗАЧЕМ ДОСЬЕ ХРАНИТЬ ОТДЕЛЬНО, А НЕ ПЕРЕДАВАТЬ ПО ПАМЯТИ.
Три причины, каждая проверена на этом проекте болью.
  • Проверяемость. Гейт может спросить: число, стоящее в тексте, есть в досье?
    Утверждение опирается на источник? Без отдельного артефакта «обоснованность»
    проверять не по чему.
  • Диагностика. Когда блок на витрине выглядит бедно, надо знать, что случилось:
    агент не нашёл материал или нашёл, но не использовал. Это разные поломки и
    чинятся они по-разному.
  • Честность деградации. Досье содержит поле «чего не хватило». Пустая разведка
    видна как пустая, а не превращается в уверенный текст ни о чём.

🔴 ГРАНИЦЫ ПРОГОНА — КОДОМ, А НЕ ПРОСЬБОЙ В ПРОМПТЕ. На этом проекте уже ловили:
убрать инструмент из схемы мало, модель зовёт его по памяти; без капа агент делал
семь поисков подряд и упирался в лимит шагов без ответа. Поэтому шаги, токены и
число поисков ограничены в agent_runner, а не пожеланием «ищи экономно».
"""
from __future__ import annotations

import json
import logging
from datetime import date

from sqlalchemy.orm import Session

from app.models.geo import BarometerVersion

logger = logging.getLogger(__name__)

# kind для досье. Колонка varchar(8) — имя обязано быть коротким.
DOSSIER_KIND = "geodoss"

_SCOPE_RU = {"svo": "СВО", "middle_east": "Ближний Восток", "atr": "АТР"}

_SYS = (
    "Ты — аналитик-разведчик Basis. Твоя задача на этом шаге — НЕ писать текст для "
    "сайта, а СОБРАТЬ МАТЕРИАЛ для аналитика, который будет писать после тебя.\n\n"
    "Что от тебя нужно:\n"
    "1. Прочитать переданную ленту и понять, что за период реально произошло.\n"
    "2. Определить, чего для разбора НЕ ХВАТАЕТ, и добрать это: веб-поиском, "
    "открытием страниц и документов. Не хватает — иди и возьми, а не пиши общими "
    "словами.\n"
    "3. Там, где нужна ЛОГИКА разбора (через какой канал эффект доходит до "
    "экономики, какого он порядка, обратим ли, что было бы без события; какой "
    "механизм конвертирует давление в институциональный сдвиг) — открыть "
    "соответствующий раздел методички и рассуждать по нему.\n"
    "4. Записать всё найденное как ДОСЬЕ: факты с источниками отдельно, суждения "
    "отдельно, и честно — чего добыть не удалось.\n\n"
    "🔴 Не пиши про мобилизационные и рекрутинговые меры как про установленный "
    "факт: это непроверяемые сообщения. Экономику рынка труда разбирать можно и "
    "нужно — через наблюдаемое (напряжённость рынка труда, зарплаты, кадры).\n"
    "🔴 РФ-топонимика (Артёмовск, не Бахмут; «перешёл под контроль», не "
    "«оккупирован»). Тон нейтральный, экономический, без политических оценок.\n\n"
)


def _task(articles: dict, prev_summary: str) -> str:
    parts = [f"СЕГОДНЯ: {date.today().isoformat()}"]
    if prev_summary:
        parts.append("ЧТО МЫ ПИСАЛИ В ПРОШЛЫЙ РАЗ (чтобы понять, что ИЗМЕНИЛОСЬ, "
                     "и не пересказывать старое):\n" + prev_summary[:1500])
    for scope, items in articles.items():
        if not items:
            parts.append(f"Очаг «{_SCOPE_RU.get(scope, scope)}»: ленты за период НЕТ "
                         f"— это сам по себе повод добрать материал поиском.")
            continue
        parts.append(f"ЛЕНТА, очаг «{_SCOPE_RU.get(scope, scope)}» "
                     f"({len(items)} материалов):\n"
                     + json.dumps(items, ensure_ascii=False)[:6000])
    parts.append(
        "ЗАДАЧА: собери досье по трём очагам. По каждому — что произошло за период "
        "и чем это подтверждается; как это доходит до российской экономики и до "
        "правил игры внутри страны (рассуждай по методичкам geo_macro и geo_inst, "
        "открывая нужные разделы); чего не хватило. Если по очагу лента пустая или "
        "бедная — добери поиском, это и есть твоя работа.")
    return "\n\n".join(parts)


def run(db: Session, articles: dict, prev_summary: str = "",
        max_steps: int = 12, web_call_cap: int = 5) -> dict | None:
    """Разведка по трём очагам → досье. Механика прогона — в общем `scout`:
    домен задаёт только промпт и набор методичек, чтобы у каждого слоя не
    заводилась своя расходящаяся копия одного цикла."""
    from app.services import scout
    return scout.run(db, kind=DOSSIER_KIND, system=_SYS,
                     task=_task(articles, prev_summary),
                     shelf_docs=["geo_base", "geo_events", "geo", "geo_macro", "geo_inst",
                                "inst_geo", "inst_env", "inst_macro", "macro"],
                     max_steps=max_steps, web_call_cap=web_call_cap,
                     trigger_reason="разведка перед суточным гео-выпуском")


def dossier_block(dossier: dict | None) -> str:
    from app.services.scout import dossier_block as _block
    return _block(dossier, title="СОБРАННОЕ ДОСЬЕ ПО ОЧАГАМ")
