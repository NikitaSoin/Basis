/**
 * Реквизиты Оператора для юридических документов — ОДНО место на весь проект.
 *
 * 🔴 ПОКА ЗДЕСЬ ПЛЕЙСХОЛДЕРЫ, документы публикуются с пометкой «проект»: оферта без
 * указания, КТО её сделал, договором не становится, а политика без оператора не
 * выполняет требование 152-ФЗ. Как только владелец даст данные — заполнить и
 * пересобрать: пометка исчезнет сама, больше править нечего.
 *
 * Что нужно: организационно-правовая форма и полное наименование (ИП Фамилия Имя
 * Отчество либо ООО «Название»), ИНН, ОГРНИП/ОГРН, адрес для корреспонденции и адрес
 * электронной почты для обращений (в том числе по персональным данным).
 */
"use strict";

const OPERATOR = {
  name: "",            // «ИП Иванов Иван Иванович» или «ООО «Базис»»
  inn: "",             // ИНН
  ogrn: "",            // ОГРНИП или ОГРН
  address: "",         // адрес для корреспонденции
  email: "",           // почта для обращений; если пусто — подставится info@inbasis.ru
  responsible: "",     // ответственный за организацию обработки персональных данных
};

const SITE = "https://inbasis.ru";
const FALLBACK_EMAIL = "info@inbasis.ru";   // реально работающий ящик отправки писем

/** Заполнены ли реквизиты настолько, чтобы документ имел силу. */
function isReady() {
  return Boolean(OPERATOR.name && OPERATOR.inn && OPERATOR.ogrn && OPERATOR.address);
}

/** Почта для обращений: заданная владельцем либо рабочий ящик платформы. */
function contactEmail() {
  return OPERATOR.email || FALLBACK_EMAIL;
}

/** Подстановка реквизитов вместо плейсхолдеров вида [ИНН] в тексте документа. */
function fill(text) {
  const email = contactEmail();
  const map = [
    [/\[полное наименование — ИП Фамилия Имя Отчество \/ ООО «…»\]/g, OPERATOR.name || "[реквизиты уточняются]"],
    [/\[полное наименование — ИП ФИО \/ ООО «…»\]/g, OPERATOR.name || "[реквизиты уточняются]"],
    [/\[Полное наименование\]/g, OPERATOR.name || "[реквизиты уточняются]"],
    [/\[полное наименование Оператора\]/g, OPERATOR.name || "[реквизиты уточняются]"],
    [/\[Наименование Исполнителя\]/g, OPERATOR.name || "Платформа Basis"],
    [/\[Наименование лица, предоставляющего информацию\]/g, OPERATOR.name || "Платформа Basis"],
    [/\[ИНН\]/g, OPERATOR.inn || "—"],
    [/\[номер\]/g, OPERATOR.ogrn || "—"],
    [/\[адрес\]/g, OPERATOR.address || "—"],
    [/\[email поддержки\]/g, email],
    [/\[email\]/g, email],
    [/\[ФИО, должность\]/g, OPERATOR.responsible || OPERATOR.name || "—"],
    [/\[дата публикации\]/g, publishDate()],
    [/\[дата\]/g, publishDate()],
  ];
  let out = text;
  for (const [re, val] of map) out = out.replace(re, val);
  return out;
}

/** Дата публикации — день сборки. Документ обязан её показывать. */
function publishDate() {
  const d = new Date();
  return `${String(d.getDate()).padStart(2, "0")}.${String(d.getMonth() + 1).padStart(2, "0")}.${d.getFullYear()}`;
}

module.exports = { OPERATOR, SITE, isReady, contactEmail, fill, publishDate };
