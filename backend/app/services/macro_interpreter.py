def _context(db: Session, limit: int | None = None) -> dict:
    """Живой контекст, в котором блок рассуждает: летопись + барометры.

    🔴 До 2026-08-01 модель видела только цифры и 12 записок ЦБ/ЦМАКП — то есть
    рассуждала о рынке, не зная, ЧТО НА ПОВЕСТКЕ. Именно из-за этого сценарии выходили
    «сценариями ради сценариев»: без ленты неоткуда узнать, что прямо сейчас реальная
    развилка — топливный кризис, а не абстрактный «бык/медведь». Летопись уже
    LLM-размечена по темам/секторам/тикерам, поэтому отбор дешёвый и точный.

    Всё в try/except: контекст — усиление, а не обязательное условие. Отсутствие
    таблицы (напр. на свежей базе) не должно ронять генерацию блока.
    """
    out: dict = {}
    try:
        from app.models.chronicle import ChronicleEntry
        limit = limit or _CHRONICLE_LIMIT
        rows = (db.query(ChronicleEntry)
                .filter(ChronicleEntry.themes.isnot(None))
                .order_by(ChronicleEntry.published_at.desc(), ChronicleEntry.id.desc())
                .limit(1200).all())
        selected = []
        for r in rows:
            if not set(r.themes or []) & set(_MACRO_THEMES):
                continue
            # Отсеиваем поток заголовков без аналитики (владелец: «все новости с
            # MarketTwits нет смысла») — иначе объёмом вытеснит содержательные разборы.
            src = f"{r.source_key or ''} {r.source_url or ''}".lower()
            if any(n in src for n in _NOISE_SOURCES):
                continue
            selected.append(r)
            if len(selected) >= limit:
                break
        # Первоисточники целиком — для содержательных материалов (разборы, статьи,
        # отраслевые обзоры). Для коротких новостных записей текста и так достаточно.
        try:
            from app.services.article_texts import ensure_full_texts
            deep = [r for r in selected if r.kind in ("article", "report")]
            ensure_full_texts(db, deep, limit=20)
        except Exception:  # noqa: BLE001
            logger.warning("Интерпретатор: дозагрузка текстов летописи не отработала", exc_info=True)
        picked = []
        for r in selected:
            picked.append({
                "date": (r.event_date or (r.published_at.date() if r.published_at else None)).isoformat()
                        if (r.event_date or r.published_at) else None,
                "kind": r.kind, "title": r.title,
                "summary": r.summary,
                "why_it_mattered": r.interpretation or None,
                "themes": r.themes, "sectors": r.sectors, "tickers": r.tickers,
                "source_url": r.source_url,
                "full_text": getattr(r, "full_text", None),
            })
        if picked:
            out["chronicle"] = picked
    except Exception:  # noqa: BLE001
        logger.warning("Интерпретатор: летопись недоступна", exc_info=True)

    for key, label in (("geo", "geo_barometer"), ("inst", "institutional_barometer")):
        try:
            from app.services.barometer_store import get_payload_with_meta
            payload = get_payload_with_meta(db, key)
            if payload:
                out[label] = _compact_barometer(payload)
        except Exception:  # noqa: BLE001
            logger.warning("Интерпретатор: барометр %s недоступен", key, exc_info=True)

    # Замеры институтов по направлениям (собственность, суды, госдоля,
    # конкуренция, регуляторная нагрузка…). Владелец 2026-08-02 просил, чтобы
    # домены обменивались материалом: макро должен видеть не только общий балл
    # институтов, но и КУДА двинулись отдельные направления — инвестиционный
    # климат и стоимость капитала объясняются именно ими, а не сводным числом.
    # Импорт мягкий: Timeweb выкатывает файлы неравномерно, и модуль-потребитель
    # может доехать раньше нового сервиса (память timeweb-uneven-file-rollout).
    try:
        from app.services.institutions_domains import for_agents as _inst_domains
        dom = _inst_domains(db)
        if dom.get("domains"):
            out["institutional_domains"] = dom
    except Exception:  # noqa: BLE001
        logger.debug("Интерпретатор: замеры институтов недоступны", exc_info=True)
    return out


# 🔴 Внутренние коды сценариев наружу НЕ ВЫХОДЯТ (владелец, 2026-08-08: «я, пользователь,
# знать не знаю про S3, S4 — ты должен сценарии объяснять словами»). Коды — язык
# геополитического барометра, удобный внутри системы и бессмысленный на витрине.
# Лечим с двух сторон: (1) в промпт кладём уже человеческие названия, чтобы модели
# нечего было цитировать; (2) на выходе подменяем то, что всё-таки просочилось.
_SCENARIO_LABELS = {
    "S1_breakthrough": "прорыв к миру (быстрое урегулирование)",
    "S2_ceasefire": "перемирие с заморозкой конфликта",
    "S3_attrition": "затяжной конфликт без разрешения (базовый сценарий)",
    "S4_escalation": "эскалация конфликта",
}
# В прозе подставляем название В КАВЫЧКАХ: падеж мехзаменой не согласуешь («при
# сохранении затяжной конфликт»), а кавычки превращают подстановку в имя сценария и
# читаются нормально в любом падеже. Это страховка на случай утечки — основное
# лечение в промпте (правило 7д) и в том, что коды в промпт вообще не попадают.
_SCENARIO_SHORT = {
    "S1": "сценария «прорыв к миру»", "S2": "сценария «перемирие»",
    "S3": "сценария «затяжной конфликт»", "S4": "сценария «эскалация»",
}
_SCENARIO_CODE_RE = re.compile(
    r"\b(S[1-4])(?:_[a-z]+)?\b(?:\s*\((?:базов\w+|текущ\w+)\))?", re.I)


def humanize_scenarios(value):
    """Рекурсивно: коды сценариев → человеческие названия (и в ключах словарей)."""
    if isinstance(value, str):
        full = _SCENARIO_LABELS.get(value)
        if full:
            return full
        return _SCENARIO_CODE_RE.sub(
            lambda m: _SCENARIO_SHORT.get(m.group(1).upper(), m.group(0)), value)
    if isinstance(value, list):
        return [humanize_scenarios(v) for v in value]
    if isinstance(value, dict):
        return {(_SCENARIO_LABELS.get(k) or humanize_scenarios(k) if isinstance(k, str) else k):
                humanize_scenarios(v) for k, v in value.items()}
    return value


def _compact_barometer(payload: dict) -> dict:
    """Из барометра берём рамку: что изменилось, чем сейчас живёт повестка, какие
    переходы возможны и на что смотреть в ближайший месяц.

    Полный барометр — десятки килобайт прозы, целиком в промпт не нужен. Но именно
    здесь лежат РЕАЛЬНЫЕ развилки (а не выдуманные «бык/медведь»): триггеры переходов
    между сценариями, вотчлист на 30 дней с ожидаемым эффектом и секторные флаги с
    обоснованием. Ровно то, чего блоку не хватало, чтобы не сочинять сценарии ради
    сценариев.
    """
    out: dict = {"as_of": payload.get("as_of")}
    summary = payload.get("summary")
    if isinstance(summary, str):
        out["what_changed"] = summary[:900]

    sc = payload.get("scenario")
    if isinstance(sc, dict):
        # 🔴 БЕЗ белого списка имён. Он здесь стоял и не совпадал со схемой барометра:
        # ждал ("current", "mix_6m", "probabilities"), а барометр отдаёт
        # current_lean / probabilities_6m / probabilities_18m / delta_explanation.
        # В снапшот проходили ОДНИ triggers — поэтому выпуск и не мог привязать
        # прогнозы к сценариям, хотя вероятности лежали рядом. Тот же тихий дрейф
        # схемы, что уже ловили в ревизоре выпуска.
        out["scenario"] = {k: (v[:400] if isinstance(v, str) else v)
                           for k, v in sc.items() if v not in (None, "", [], {})}
    elif isinstance(sc, str):
        out["scenario"] = sc[:400]

    watch = payload.get("watchlist_30d")
    if isinstance(watch, list):
        out["watchlist_30d"] = [
            {k: w.get(k) for k in ("signal", "window", "expected_effect") if w.get(k)}
            for w in watch[:8] if isinstance(w, dict)
        ]

    flags = payload.get("sector_flags")
    if isinstance(flags, list):
        out["sector_flags"] = [
            {k: (str(f.get(k))[:260] if k == "reasoning" else f.get(k))
             for k in ("sector", "direction", "channel", "reasoning") if f.get(k)}
            for f in flags[:10] if isinstance(f, dict)
        ]

    alerts = [a.get("label") or a.get("text") or a.get("title") if isinstance(a, dict) else a
              for a in (payload.get("alerts") or [])[:6]]
    alerts = [str(a)[:200] for a in alerts if a]
    if alerts:
        out["alerts"] = alerts
    return humanize_scenarios({k: v for k, v in out.items() if v})


def _previous_issues(db: Session, limit: int = 4) -> list[dict]:
    """Прошлые выпуски этого же блока — чтобы модель видела СВОЙ трекшен.

    🔴 До 2026-08-01 каждый прогон начинался с чистого листа: модель не знала, что сама
    писала вчера, и не могла ни признать пересмотр оценки, ни сослаться на него. Для
    платформы, чья главная ценность — доверие, аналитик, молча переписывающий прогноз
    задним числом, хуже, чем аналитик, который говорит «месяц назад ждали иначе, вот
    почему поменяли». Отдаём только каркас прошлого суждения (вердикт + путь ставки +
    развилки), не весь JSON — иначе модель начнёт копировать формулировки.
    """
    rows = (db.query(MacroInterpretation)
            .order_by(MacroInterpretation.generated_at.desc()).limit(limit).all())
    out = []
    for r in rows:
        s = r.sections or {}
        out.append({
            "_note": "ПРОШЛОЕ СУЖДЕНИЕ, не данные. Числа отсюда брать нельзя.",
            "generated_at": r.generated_at.date().isoformat(),
            "headline": _strip_numbers(s.get("headline")),
            "rate_path": _strip_numbers((s.get("rate_path") or {}).get("base")
                                        if isinstance(s.get("rate_path"), dict) else None),
            "forks": [f.get("event") for f in (s.get("forks") or []) if isinstance(f, dict)][:4],
            # старый формат (до переделки) — чтобы переход не потерял историю
            "legacy_theses": [_strip_numbers(t.get("claim"))
                              for t in (s.get("theses") or []) if isinstance(t, dict)][:3],
        })
    return out


def _strip_numbers(text: str | None) -> str | None:
    """Убирает числа из прошлых формулировок, оставляя смысл.

    🔴 Найдено 2026-08-01 на первом же прогоне с памятью: прошлый выпуск содержал
    ошибочное «инфляционные ожидания 14,7%» (модель тогда спутала наблюдаемую инфляцию
    из записки ЦБ с ожиданиями), и следующий выпуск ЭТО СКОПИРОВАЛ. Память, задуманная
    как механизм доверия, начала закреплять ошибку — самовоспроизводящаяся неправда
    опаснее разового промаха. Смысл суждения («ждали паузу в снижении») для трекшена
    сохраняется, а числовые утверждения модель обязана заново взять из indicators.
    """
    if not text:
        return text
    return re.sub(r"\d+[.,]?\d*\s*%?", "…", text)


# Показатели, чьё числовое значение проверяем в тексте вывода: (код, метрика,
# регулярка-триггер «о чём идёт речь», допуск). Проверяем только те, где ошибка
# критична и распознаётся однозначно.
_NUMBER_CHECKS = (
    ("inflation_expectations", "level", r"инфляционн\w*\s+ожидани\w*|ожидани\w*\s+населени", 0.35),
    ("key_rate", "level", r"ключев\w*\s+ставк|ставка\s+ЦБ", 0.30),
)


def _check_numbers(sections: dict, snapshot: dict) -> list[str]:
    """Ищет в тексте вывода числа, приписанные показателю, но не совпадающие с данными.

    Логика намеренно узкая: берём предложение, где упомянут показатель, вытаскиваем
    из него проценты и сверяем с фактическим значением. Если НИ ОДНО число рядом не
    похоже на факт — это подмена (модель взяла величину из чужого контекста).
    Прогнозные фразы («до 11-12% к концу года») законно содержат другие числа,
    поэтому нарушением считаем только случай, когда фактического значения рядом нет
    вовсе, а какое-то число есть.
    """
    facts = {(i.get("code"), i.get("metric")): i for i in snapshot.get("indicators") or []}
    text = json.dumps(sections, ensure_ascii=False)
    # Режем по ГРАНИЦАМ ПОЛЕЙ JSON, а не по знакам препинания: в одном предложении
    # штатно соседствуют несколько показателей («ставка 14%, но ожидания 14,7%»), и
    # разрез по точке отрывал число от его показателя — на этом валидатор дал ложное
    # срабатывание в первом же прогоне (2026-08-01).
    chunks = re.split(r"\",\s*\"|\":\s*\"", text)
    out: list[str] = []
    for code, metric, trigger, tol in _NUMBER_CHECKS:
        ind = facts.get((code, metric))
        if not ind or ind.get("current_value") is None:
            continue
        actual = float(ind["current_value"])
        for chunk in chunks:
            if not re.search(trigger, chunk, re.I):
                continue
            nums = [float(n.replace(",", ".")) for n in re.findall(r"\d+[.,]?\d*(?=\s*%)", chunk)]
            if not nums:
                continue
            if any(abs(n - actual) <= tol for n in nums):
                continue  # факт рядом есть — прогнозные числа в том же предложении ок
            out.append(
                f"«{ind.get('title') or code}» сейчас {actual}{ind.get('unit') or ''} "
                f"(на {ind.get('as_of')}), а в тексте рядом стоят {nums} — "
                f"похоже, число взято из чужого источника"
            )
            break
    return out


# Сколько всего времени отпущено выпуску, прежде чем НЕОБЯЗАТЕЛЬНЫЕ шаги начинают
# отбрасываться. Ночью выпуск стоит в 07:15, а в 07:40 стартует следующий крон:
# затянувшаяся генерация наложится на него и будет грузить инстанс вдвоём — на этих
# граблях уже вешали БД (LLM/FRED-кроны). Выпуск важнее ревизии: она замечания, а
# не содержание.
_SOFT_BUDGET_SEC = 20 * 60


# Сколько раз выпуск возвращается на доработку. Владелец (2026-08-03): критик
# «блокировать не должен, но ошибки должны быть исправлены — возможно, в особых
# случаях несколько итераций: агент сделал, критик дал обратку, агент исправил,
# критик указал на шероховатости и отправил переделывать, агент переделал».
# Три прохода — предел разумного: каждый стоит одной генерации выпуска, а по логам
# основная часть замечаний снимается на первом-втором.
_MAX_LOGIC_PASSES = 3


def _fix_instruction(prev_sections: dict, review: dict) -> str:
    """Задание на ТОЧЕЧНУЮ правку: предыдущий текст + замечания критика.

    🔴 Почему не «сгенерируй заново с оглядкой на замечания» (так было до 2026-08-03).
    Регенерация с нуля чинила указанное, но заносила НОВЫЕ ошибки в местах, которых
    замечания не касались: на живых прогонах было 2 грубых → стало 3, и 3 → 4. Модель
    каждый раз писала другой текст, а не исправляла свой. Отдаём ей собственный
    предыдущий вариант и просим тронуть только то, на что указал критик, — тогда
    итерации сходятся, а не блуждают.
    """
    from app.services.macro_logic_critic import format_for_prompt
    return (
        "🔴 ЭТО ДОРАБОТКА, А НЕ НОВЫЙ ВЫПУСК. Ниже — ТВОЙ предыдущий вариант и разбор "
        "критика макро-логики. Верни тот же выпуск целиком (та же структура), исправив "
        "ТОЛЬКО то, на что указал критик, и всё, что от этого зависит по смыслу. "
        "Формулировки, которые критик не трогал, сохраняй как есть — переписывание "
        "здорового текста заносит новые ошибки. Если считаешь замечание неверным, не "
        "молчи: оставь своё утверждение и добавь в него оговорку, снимающую претензию.\n\n"
        + format_for_prompt(review)
        + "\n\nТВОЙ ПРЕДЫДУЩИЙ ВАРИАНТ:\n"
        + json.dumps({"sections": prev_sections}, ensure_ascii=False)
    )


def _logic_score(review: dict) -> tuple[int, int]:
    """Чем меньше — тем лучше: сначала грубые, при равенстве — общее число замечаний."""
    return (review.get("hard_count") or 0, len(review.get("issues") or []))


def _logic_loop(db: Session, sections: dict, ask, t0: float,
                expectations: list[dict] | None = None,
                tone_guard: dict | None = None) -> tuple[dict, dict]:
    """Цикл «выпуск → критик → доработка → критик», пока грубые не исчерпаны.

    Критик НЕ блокирует публикацию (владелец): даже с оставшимися замечаниями выпуск
    выходит — но выходит ЛУЧШАЯ из полученных версий, а не последняя.
    """
    from app.services.macro_logic_critic import review_logic

    review = review_logic(db, sections, expectations, tone_guard)
    best_sections, best_review = sections, review
    passes = []
    for attempt in range(1, _MAX_LOGIC_PASSES + 1):
        if not (best_review.get("hard_count") or 0):
            break
        # Каждый заход стоит примерно одной генерации выпуска. Идём на него, только
        # если до мягкого предела остаётся столько же с запасом: ночной выпуск не
        # должен наползти на следующий крон (07:40) — на этом уже вешали инстанс.
        spent = time.monotonic() - t0
        per_pass = spent / attempt
        # Потолок цикла — доля бюджета, а не весь: остаток нужен ревизору чисел,
        # иначе доработки логики съедят его целиком и выпуск выйдет непроверенным.
        ceiling = _SOFT_BUDGET_SEC * 0.7
        if spent + per_pass * 1.3 > ceiling:
            logger.warning("Интерпретатор: логика — %s грубых, но бюджет исчерпан "
                           "(потрачено %.0f с из %.0f) — публикуем как есть",
                           best_review["hard_count"], spent, ceiling)
            best_review = {**best_review, "stopped": "budget"}
            break
        logger.warning("Интерпретатор: логика — %s грубых замечаний, доработка %s/%s",
                       best_review["hard_count"], attempt, _MAX_LOGIC_PASSES)
        out = ask(_fix_instruction(best_sections, best_review))
        fixed = out.get("sections") if isinstance(out, dict) else None
        if not fixed:
            logger.warning("Интерпретатор: доработка %s не вернула sections", attempt)
            break
        after = review_logic(db, fixed, expectations, tone_guard)
        passes.append({"pass": attempt, "before": _logic_score(best_review)[0],
                       "after": _logic_score(after)[0]})
        # 🔴 Берём ЛУЧШУЮ версию, а не последнюю: «переписал» ≠ «стало лучше».
        if _logic_score(after) <= _logic_score(best_review):
            best_sections, best_review = fixed, after
        else:
            # Доработка ухудшила логику — дальше долбить бессмысленно, откатываемся
            # к лучшей версии и выходим.
            logger.warning("Интерпретатор: доработка %s ухудшила логику (%s → %s грубых) "
                           "— оставлена предыдущая версия", attempt,
                           _logic_score(best_review)[0], _logic_score(after)[0])
            best_review = {**best_review, "stopped": "worse", "worse_at_pass": attempt}
            break
    if passes:
        best_review = {**best_review, "passes": passes,
                       "hard_before": passes[0]["before"],
                       "rewritten": best_sections is not sections}
    return best_sections, best_review


def generate(db: Session) -> MacroInterpretation:
    """Сгенерировать интерпретацию (Pro reasoning) и сохранить срез."""
    t0 = time.monotonic()
    snapshot = gather_snapshot(db)
    # 🔴 Мост «макро → сектор» (владелец, 2026-08-09) — отдельным блоком после
    # основной методички: секторную часть выпуска положено строить по нему, а не по
    # общим соображениям. Целиком документ не кладём — только каркас (цепочка
    # трансмиссии, сквозные драйверы, сводная таблица чувствительностей, чек-лист
    # ошибок); подробные секторные разделы нужны per-company контурам, не выпуску.
    from app.services.macro_sector_playbook import core as _sector_core, drivers_digest
    bridge = _sector_core()
    drivers = drivers_digest()
    if drivers:
        bridge = (bridge + "\n\n" + drivers) if bridge else drivers
    if not bridge:
        logger.warning("Интерпретатор: методичка «макро → сектор» недоступна — "
                       "секторный блок строится без неё")
    system = _methodology() + _OUTPUT_SPEC + (("\n\n" + bridge) if bridge else "")
    user = ("Данные платформы на текущий момент (используй конкретные значения):\n\n"
            + json.dumps(snapshot, ensure_ascii=False, indent=1))
    model = llm.pro_model()
    # max_tokens поднят с 8192: новый структурированный scenarios (3 сценария × 3 поля)
    # добавил объём, и с thinking=True рассуждение тоже расходует общий бюджет —
    # раньше не хватало на последний ключ scenarios, JSON приходил валидным, но без него.
    def _ask(extra: str = "") -> dict:
        return llm.complete(system, user + ("\n\n" + extra if extra else ""),
                            json_mode=True, thinking=True,
                            model=model, max_tokens=16000, temperature=0.4)

    out = _ask()
    sections = out.get("sections") if isinstance(out, dict) else None
    if not sections:
        raise llm.LLMError("Интерпретатор: модель не вернула sections")

    # 🔴 Код-проверка чисел с ОДНОЙ автопоправкой (2026-08-01). История вопроса:
    # модель четыре прогона подряд писала «инфляционные ожидания 14,7%» при
    # фактических 12,2% — брала первое похожее число из прозы записки ЦБ (там 14,7 —
    # это «наблюдаемая инфляция», другая величина того же опроса). Не помогли ни
    # самоописательные имена полей, ни два прямых запрета в промпте, ни блок key_facts
    # с готовыми формулировками первым в снапшоте. Вывод: уговорами класс ошибки не
    # лечится, нужна проверка кодом — тот же принцип, что в «ОТК данных» Макрообзора.
    # 🔴 АВТОГЕЙТ ВЫПУСКА (2026-08-02). Проверяет КОД, не LLM — тот же принцип, что в
    # «ОТК данных». Раньше проверка жила только у пилотного агента по одной компании, а
    # самый дорогой по доверию артефакт платформы выходил без неё.
    # Гейт НЕ роняет блок: reject только на грубых структурных дефектах (тогда на
    # витрине остаётся предыдущий срез — это честнее пустого экрана), всё остальное
    # публикуется с записанными заметками.
    # 🔴 Критик макро-логики. Худшие дефекты выпуска были не в числах, а в СВЯЗКАХ:
    # «рост нефти → инфляция» для страны-экспортёра, «дисконт → дефицит бюджета»,
    # «инвестиции упали → слабый ВВП квартала» (лаг годы). Каждое утверждение по
    # отдельности выглядит грамотно, ошибка — в стрелке между ними. Владелец просил
    # «агента-советника, который скажет: ты криво понял макру» — это он.
    logic = None
    if sections and os.environ.get("MACRO_LOGIC_CRITIC", "1") == "1":
        try:
            sections, logic = _logic_loop(db, sections, _ask, t0,
                                          snapshot.get("external_expectations"),
                                          snapshot.get("tone_guard"))
        except Exception:  # noqa: BLE001
            logger.warning("Интерпретатор: критик логики не отработал", exc_info=True)

    # Подчистка внутреннего жаргона ПОСЛЕ всех доработок: критик и ревизор видят текст
    # как есть, а на витрину идёт уже человеческий язык. Коды сценариев в промпт не
    # попадают (см. humanize_scenarios в _compact_barometer), но модель знает их из
    # записок и иногда пишет сама — «При сохранении S3» читателю не говорит ничего.
    sections = humanize_scenarios(sections)

    verdict, gate_notes = "ok", []
    try:
        from app.services.macro_release_gate import check_release
        verdict, gate_notes = check_release(sections, snapshot)
        if gate_notes:
            logger.warning("Интерпретатор: гейт (%s): %s", verdict, gate_notes[:10])
    except Exception:  # noqa: BLE001
        logger.warning("Интерпретатор: гейт не отработал", exc_info=True)
    if verdict == "reject":
        raise llm.LLMError(f"Выпуск отклонён гейтом: {gate_notes[:5]}")

    # Несуществующие тикеры убираем ДО сохранения: фронт делает из каждого кнопку
    # перехода на карточку, и «VTB» вместо «VTBR» — это ссылка в никуда в выпуске.
    try:
        from app.services.macro_release_gate import strip_unknown_tickers
        removed = strip_unknown_tickers(sections, snapshot)
        if removed:
            logger.warning("Интерпретатор: убраны несуществующие тикеры: %s", removed)
            gate_notes = list(gate_notes) + [f"stripped:{','.join(removed)}"]
    except Exception:  # noqa: BLE001
        logger.warning("Интерпретатор: чистка тикеров не отработала", exc_info=True)

    # Агент-ревизор: выборочно проверяет числовые утверждения, поданные как ФАКТ.
    # Гейт ловит формальное (структура, сверка с key_facts), ревизор — то, ради чего
    # надо пойти и посмотреть источник. Выпуск не переписывает: правка чужого суждения
    # моделью — подмена автора, а не проверка.
    review = None
    elapsed = time.monotonic() - t0
    if elapsed > _SOFT_BUDGET_SEC:
        review = {"checked": 0, "issues": [],
                  "note": f"ревизия пропущена: выпуск занял {elapsed / 60:.0f} мин"}
        logger.warning("Интерпретатор: ревизия пропущена, выпуск занял %.0f мин", elapsed / 60)
    elif os.environ.get("MACRO_RELEASE_REVIEW", "1") == "1":
        try:
            from app.services.macro_release_reviewer import review_release
            review = review_release(db, sections, snapshot=snapshot)
            if review.get("issues"):
                logger.warning("Интерпретатор: ревизор нашёл спорные утверждения: %s",
                               [i["claim"][:80] for i in review["issues"]])
        except Exception:  # noqa: BLE001
            logger.warning("Интерпретатор: ревизор не отработал", exc_info=True)

    row = MacroInterpretation(
        sections=sections, generated_at=datetime.now(timezone.utc),
        model_used=f"{llm.provider_info().get('provider')}:{model}",
        source_snapshot={"indicators_count": len(snapshot["indicators"]),
                         "has_rate": bool(snapshot["rate"]), "docs": len(snapshot["analytics"]),
                         # Наблюдаемость: по этим флагам видно, КАКОЙ версией кода
                         # сгенерирован срез. Без них при отладке нельзя отличить
                         # «фикс не сработал» от «фикс ещё не доехал на бой» —
                         # ровно на это ушло 4 лишних прогона 2026-08-01.
                         "has_key_facts": bool(snapshot.get("key_facts")),
                         # сколько показателей получили внешний контекст ожиданий —
                         # иначе «блок не сработал» и «модель его проигнорировала»
                         # снаружи неотличимы
                         "external_expectations": [
                             e.get("indicator") for e in (snapshot.get("external_expectations") or [])],
                         "gate": verdict, "gate_notes": gate_notes[:12] or None,
                         "logic": logic,
                         "review": review,
                         "chronicle": len((snapshot.get("context") or {}).get("chronicle") or []),
                         "prev_issues": len(snapshot.get("previous_issues") or [])})
    db.add(row)
    db.commit()
    db.refresh(row)
    logger.info("Интерпретатор: сгенерирован срез #%d (%s)", row.id, row.model_used)
    return row


# ────────────────── фоновый запуск (обход таймаута прокси) ──────────────────
# 🔴 Владелец 2026-08-01: «не надо резать, нужно целиком». Полные первоисточники дают
# ~490k токенов входа, и генерация не укладывается в таймаут прокси Timeweb — ручное
# обновление отдавало 502 через 219 секунд. Резать контекст ради HTTP-таймаута
# неправильно: ограничение чисто транспортное, окно модели свободно на 53%.
# Решение: HTTP-запрос больше НЕ ЖДЁТ генерацию. POST ставит задачу в фоновый поток и
# сразу отвечает, фронт опрашивает GET. Ночной крон вызывает generate() напрямую —
# ему прокси не мешает.
_run_lock = threading.Lock()
_run_state: dict = {"running": False, "started_at": None, "error": None, "finished_at": None}


def run_state() -> dict:
    """Статус фоновой генерации для фронта (идёт / когда началась / чем кончилась)."""
    st = dict(_run_state)
    st["started_at"] = st["started_at"].isoformat() if st["started_at"] else None
    st["finished_at"] = st["finished_at"].isoformat() if st["finished_at"] else None
    return st


def start_background_generation() -> dict:
    """Поставить генерацию в фон. Повторный запуск во время работы игнорируется —
    каждый прогон стоит денег и минут, дважды кликнутая кнопка не должна их удваивать."""
    with _run_lock:
        if _run_state["running"]:
            return {"started": False, "reason": "already_running", **run_state()}
        _run_state.update(running=True, started_at=datetime.now(timezone.utc),
                          error=None, finished_at=None)

    def _worker() -> None:
        from app.db.session import SessionLocal
        db = SessionLocal()
        try:
            row = generate(db)
            logger.info("Интерпретатор: фоновая генерация завершена (срез #%s)", row.id)
            with _run_lock:
                _run_state.update(running=False, error=None,
                                  finished_at=datetime.now(timezone.utc))
        except Exception as e:  # noqa: BLE001
            logger.exception("Интерпретатор: фоновая генерация упала")
            with _run_lock:
                _run_state.update(running=False, error=str(e)[:300],
                                  finished_at=datetime.now(timezone.utc))
        finally:
            db.close()

    threading.Thread(target=_worker, name="macro-interpretation", daemon=True).start()
    return {"started": True, **run_state()}


def get_latest(db: Session) -> MacroInterpretation | None:
    return db.query(MacroInterpretation).order_by(MacroInterpretation.generated_at.desc()).first()
