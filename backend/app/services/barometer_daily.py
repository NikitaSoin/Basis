    # требовала новые поля.
    # Лечим не уговором, а входом: блоки, собранные по устаревшей форме, из
    # «вчерашнего» удаляются. Копировать нечего — модель собирает заново.
    prev_for_prompt, dropped = _drop_stale_shape(prev)
    stale_note = ""
    if dropped:
        stale_note = ("🔴 ВНИМАНИЕ: " + ", ".join(dropped) + " — вчерашние блоки "
                      "собраны по УСТАРЕВШЕЙ форме и удалены из входа. Собери их "
                      "заново по текущей спецификации, со всеми новыми полями. "
                      "Правило стабильности на смену формы НЕ распространяется.\n\n")

    user = (
        (dossier_text + "\n\n" if dossier_text else "")
        + stale_note
        + "ВЧЕРАШНИЙ БАРОМЕТР (отправная точка; сохраняй значения, если лента не даёт "
        "основания их менять):\n"
        + json.dumps(prev_for_prompt, ensure_ascii=False, indent=1)[:60000]
        + f"\n\nСВЕЖАЯ ЛЕНТА ПО ОЧАГАМ (за {window_days} дней, {total} статей):\n"
        + json.dumps(articles, ensure_ascii=False, indent=1)
        + f"\n\nСЕГОДНЯ: {date.today().isoformat()}"
    )

    try:
        from app.services import analyst
        fresh = analyst.run(
            db, system=system, task=user,
            shelf_docs=["geo_base", "geo_events", "geo", "geo_macro", "geo_inst",
                        "inst_geo", "inst_env", "inst_macro"],
            max_steps=10, budget=180_000, final_max_tokens=20_000,
            final_instruction="Верни JSON строго в формате из твоей роли (ключи "
                              "as_of, subindices, scenario, regions, sector_flags, "
                              "watchlist_30d, summary, methodology_used).",
            label="barometer_daily")
        if fresh is None:
            raise llm.LLMError("аналитик не вернул валидный барометр")
    except llm.LLMError as e:
        row = BarometerVersion(kind="geo", source="auto", status="rejected",
                               payload=None, gate_notes=[f"LLM недоступен: {e}"],
                               parent_id=prev_row.id, trigger_reason="ежедневная пересборка")
        db.add(row); db.commit(); db.refresh(row)
        logger.warning("barometer_daily: LLM недоступен (%s) — версия не опубликована", e)
        return row

    if not isinstance(fresh, dict) or not fresh.get("subindices"):
        row = BarometerVersion(kind="geo", source="auto", status="rejected",
                               payload=None, gate_notes=["ответ без subindices"],
                               parent_id=prev_row.id, trigger_reason="ежедневная пересборка")
        db.add(row); db.commit(); db.refresh(row)
        return row

    # поля, которые модель могла не вернуть, — переносим со вчера, чтобы витрина
    # не потеряла блок целиком из-за одного пропущенного ключа
    for k in ("kb_version", "barometer", "implied_market", "premortem", "handoff",
              "sources", "data_flags"):
        if k not in fresh and k in prev:
            fresh[k] = prev[k]

    # То же ВНУТРИ каждого очага. Найдено на боевом прогоне 2026-08-02: один и тот
    # же промпт то возвращает regions.<очаг>.barometer/scenarios, то молча их
    # опускает — при суточной пересборке очаг случайным образом терял бы свой балл
    # и лестницу сценариев, и витрина откатывалась бы на общий рыночный показатель.
    # Переносим вчерашнее значение вместо потери (данные не выдумываются: это ровно
    # то, что уже было опубликовано вчера).
    carried: list[str] = []
    prev_regions = prev.get("regions") or {}
    for rkey, r in (fresh.get("regions") or {}).items():
        if not isinstance(r, dict):
            continue
        prev_r = prev_regions.get(rkey) or {}
        for field in ("barometer", "scenarios", "sector_flags"):
            if not r.get(field) and prev_r.get(field):
                r[field] = prev_r[field]
                carried.append(f"{rkey}.{field}: не вернулось — перенесено со вчера")

    # 🔴 Числовые баллы остроты вычищаем ПОСЛЕ переноса со вчера. Иначе они вернулись
    # бы через carry-over: модель их больше не возвращает, а вчерашнее значение
    # подставляется как «пропущенный ключ» — и убранный с витрины барометр воскресает
    # в данных (владелец 2026-08-10: «убери барометр, не надо его считать»).
    _drop_scores(fresh)

    fresh, notes = _gate(fresh, prev)
    notes = carried + notes
    fresh = _sanitize_sources(fresh)

    ok, why = compliance_ok(fresh)
    if not ok:
        row = BarometerVersion(kind="geo", source="auto", status="rejected",
                               payload=None, gate_notes=(notes + [why]),
                               parent_id=prev_row.id, trigger_reason="ежедневная пересборка")
        db.add(row); db.commit(); db.refresh(row)
        logger.warning("barometer_daily: комплаенс-блок (%s) — published не меняем", why)
        return row

    fresh.setdefault("as_of", date.today().isoformat())
    # дата ЭКСПЕРТНОГО якоря сохраняется отдельно — витрина показывает её рядом,
    # чтобы не создавать иллюзию, что вся калибровка сделана сегодня
    expert = barometer_store.last_expert(db, "geo")
    meta_anchor = (expert.payload or {}).get("as_of") if expert else prev.get("as_of")

    # Витрина (barometer_store.current_row) берёт ПОСЛЕДНЮЮ published по created_at,
    # поэтому прежнюю версию помечать не нужно — она просто перестаёт быть последней
    # и остаётся в истории (barometer_history строит по ней таймлайн ревизий).
    fresh.setdefault("expert_anchor_as_of", meta_anchor)
    row = BarometerVersion(kind="geo", source="auto", status="published",
                           payload=fresh, gate_notes=notes or None,
                           parent_id=prev_row.id,
                           trigger_reason="ежедневная пересборка",
                           model_used=f"{llm.provider_info().get('provider')}:{llm.pro_model()}")
    db.add(row); db.commit(); db.refresh(row)
    logger.info("barometer_daily: барометр пересобран (версия #%d, заметок гейта: %d)",
                row.id, len(notes))
    return row
