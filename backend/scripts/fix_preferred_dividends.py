"""Карточка префа показывала дивиденд ОБЫКНОВЕННОЙ акции.

🔴 ЧТО НАЙДЕНО (2026-08-09, при разборе 11 расхождений по дивидендам).
Блок «Дивиденды» карточки префа у пяти пар — побайтовая копия карточки обычки:
поле `dps` несёт выплату по обыкновенной акции, хотя примечание В ТОЙ ЖЕ СТРОКЕ
документирует другую, преференциальную сумму. Для держателя префа это не мелкая
неточность, а единственное число, ради которого бумагу и держат: у Сургутнефтегаза
карточка обещала 0,90 ₽ вместо 8,50 ₽ — почти в десять раз меньше, и дивдоходность
на экране получалась соответствующая.

🔴 ПОЧЕМУ ЭТО НЕ ВЫДУМЫВАНИЕ ЧИСЕЛ. Каждое значение ниже взято из примечания той
же строки той же карточки (там оно записано аналитиком со ссылкой на веб-проверку),
а для Сургутнефтегаза дополнительно сходится со справочником биржи: в rates.csv
SNGSP = 8,5 ₽ при SNGS = 0,9 ₽. То есть мы не добавляем новый факт, а приводим
поле в соответствие с фактом, который в карточке УЖЕ записан прозой.

🔴 ЧЕГО СКРИПТ НЕ ДЕЛАЕТ. Не трогает карточки обыкновенных акций — там значение
верное. Не трогает годы, где примечание не называет отдельную сумму по префу:
у части эмитентов (Сбербанк, Татнефть) выплата на ао и ап действительно равна, и
«одинаковые числа» там не дефект. Пары, где совпадение не объяснено примечанием,
остаются в списке на ручную проверку — молча их выравнивать было бы хуже.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COMPANIES = ROOT / "companies"

# тикер префа -> {год: (было — дивиденд обычки, стало — дивиденд префа)}
# Значения «стало» процитированы из примечания соответствующей строки карточки.
FIXES: dict[str, dict[int, tuple[float, float]]] = {
    "SNGSP": {2020: (0.7, 6.72), 2021: (0.8, 4.73), 2023: (0.85, 12.29),
              2024: (0.9, 8.50)},
    "KGKCP": {2022: (1.67, 3.15), 2023: (1.38, 5.62), 2024: (1.3023, 6.29)},
    "VRSBP": {2025: (2.577, 17.989)},
    "SVETP": {2025: (0.0448, 0.1716)},
    "MISBP": {2025: (1.98, 6.21)},
    # Вторая волна: найдена сверкой со справочником биржи. Там DIVIDENDVALUE ведётся
    # ПО БУМАГЕ, и у этих трёх пар биржа различает ао и ап, а карточка — нет.
    "KROTP": {2023: (0.1, 0.13)},          # примечание: «По префам — 0,13 руб»
    "RTKMP": {2024: (2.71, 6.25)},         # примечание: «ао 2,71 руб., ап 6,25 руб.»
    "KZOSP": {2023: (6.22, 0.25),          # примечание: «Преф 0,25 руб.»
              2024: (4.15, 0.25),          # см. _INFERRED — уставная фиксированная
              2025: (2.85, 0.25)},         # примечание: «2,85 руб. ао + 0,25 руб. ап»
}

# 🔴 Годы, где сумма по префу взята НЕ из примечания этой строки, а выведена из
# соседних лет: у Казаньоргсинтеза преф платит уставную фиксированную величину —
# 0,25 ₽ и в 2023, и в 2025 (оба года записаны в карточке прозой), и столько же
# показывает справочник биржи сейчас. Помечаем это в примечании как оценку, а не
# выдаём за подтверждённый факт: у платформы три уровня достоверности, и вывод по
# смежным годам — второй, а не первый.
_INFERRED = {("KZOSP", 2024)}
_INFERRED_MARK = ("Оценка: сумма по префу за этот год отдельно не подтверждена — "
                  "принята уставная фиксированная величина, как в соседних годах.")

_MARK = "Показан дивиденд по привилегированной акции."


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()

    changed, skipped = [], []
    for ticker, years in FIXES.items():
        path = COMPANIES / ticker / "governance.json"
        if not path.exists():
            skipped.append(f"{ticker}: нет governance.json")
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        hist = ((data.get("dividends") or {}).get("history") or [])
        touched = False
        for year, (expect_old, new) in years.items():
            row = next((h for h in hist if h.get("year") == year), None)
            if row is None:
                skipped.append(f"{ticker} {year}: строки нет — пропуск")
                continue
            cur = row.get("dps")
            # 🔴 Предохранитель: правим ТОЛЬКО если в поле лежит ровно та величина
            # обычки, которую мы нашли при разборе. Иначе карточку уже поправили
            # руками или другой сессией — и слепая перезапись стёрла бы верное.
            try:
                cur_f = float(cur)
            except (TypeError, ValueError):
                skipped.append(f"{ticker} {year}: dps={cur!r} не число — пропуск")
                continue
            if abs(cur_f - expect_old) > 0.0001:
                skipped.append(f"{ticker} {year}: сейчас {cur}, ожидалось {expect_old} "
                               f"— карточка изменилась, не трогаю")
                continue
            row["dps"] = new
            note = (row.get("note") or "").strip()
            mark = _MARK
            if (ticker, year) in _INFERRED:
                mark = f"{_MARK} {_INFERRED_MARK}"
            if _MARK not in note:
                row["note"] = f"{mark} {note}".strip()
            changed.append(f"{ticker} {year}: {expect_old} → {new} ₽")
            touched = True
        if touched and args.write:
            path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n",
                            encoding="utf-8")

    head = "ИСПРАВЛЕНО" if args.write else "БУДЕТ ИСПРАВЛЕНО (сухой прогон)"
    print(f"{head}: {len(changed)}")
    for c in changed:
        print("   ", c)
    if skipped:
        print(f"пропущено: {len(skipped)}")
        for s in skipped:
            print("   ", s)
    return 0


if __name__ == "__main__":
    sys.exit(main())
