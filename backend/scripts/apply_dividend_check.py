def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()

    done, skipped = [], []
    for ticker, edits in UPDATES.items():
        path = COMPANIES / ticker / "governance.json"
        if not path.exists():
            skipped.append(f"{ticker}: нет governance.json")
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        div = data.setdefault("dividends", {})
        hist = div.setdefault("history", [])
        touched = False
        for e in edits:
            year = e["year"]
            row = next((h for h in hist if h.get("year") == year), None)
            if row is None:
                row = {"year": year}
                hist.append(row)
                done.append(f"{ticker} {year}: строка добавлена")
            if "dps" in e:
                if row.get("dps") == e["dps"]:
                    skipped.append(f"{ticker} {year}: dps уже {e['dps']} — пропуск")
                else:
                    done.append(f"{ticker} {year}: dps {row.get('dps')!r} → {e['dps']}")
                    row["dps"] = e["dps"]
            if "paid" in e and row.get("paid") is not e["paid"]:
                done.append(f"{ticker} {year}: paid {row.get('paid')!r} → {e['paid']}")
                row["paid"] = e["paid"]
            if e.get("note"):
                row["note"] = e["note"]
            elif e.get("note_add"):
                cur = (row.get("note") or "").strip()
                if e["note_add"] not in cur:
                    row["note"] = f"{cur} {e['note_add']}".strip()
            touched = True
        # порядок по годам — карточка читается сверху вниз, вставка в хвост ломает вид
        hist.sort(key=lambda h: h.get("year") or 0)
        if touched and args.write:
            path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n",
                            encoding="utf-8")

    print(f"{'ПРИМЕНЕНО' if args.write else 'БУДЕТ ПРИМЕНЕНО (сухой прогон)'}: {len(done)}")
    for d in done:
        print("   ", d)
    if skipped:
        print(f"пропущено: {len(skipped)}")
        for s in skipped:
            print("   ", s)
    return 0


if __name__ == "__main__":
    sys.exit(main())
