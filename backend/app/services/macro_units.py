"""Единицы макропоказателей человеческим языком.

🔴 Владелец, 2026-08-09: «4,36 usd/bbl — используй значок доллара, а баррели пиши
по-русски, непонятно сейчас».

В базе единица хранится машинным кодом («usd/bbl», «usd/mt»): так её отдают источники,
по ней считает код, и переименовывать её в БД нельзя — сломается сверка. Поэтому перевод
живёт ОДНИМ словарём здесь и применяется на выходе: в API витрины и в текстах, которые
читает человек. Символ валюты идёт ПЕРЕД числом («$4,36 / барр.»), как принято в русской
финансовой записи, поэтому единица разделена на префикс и суффикс, а не склеивается
хвостом.
"""
from __future__ import annotations

# unit из БД → (префикс перед числом, суффикс после числа)
_UNITS: dict[str, tuple[str, str]] = {
    "%": ("", "%"),
    "%ВВП": ("", "% ВВП"),
    "usd": ("$", ""),
    "usd/bbl": ("$", " / барр."),
    "usd/mt": ("$", " / т"),
    "usd/st": ("$", " / короткую т"),
    "usd/kg": ("$", " / кг"),
    "usd/oz": ("$", " / унцию"),
    "usd/mmbtu": ("$", " / млн БТЕ"),
    "usd/dmtu": ("$", " / сухую т"),
    "usd/mbf": ("$", " / тыс. досковых футов"),
    "руб": ("", " ₽"),
    "₽": ("", " ₽"),
    "руб/т": ("", " ₽ / т"),
    "млрд ₽": ("", " млрд ₽"),
    "трлн руб": ("", " трлн ₽"),
    "ед": ("", " ед."),
    "индекс": ("", " пунктов"),
    "п": ("", " пунктов"),
}


def parts(unit: str | None) -> tuple[str, str]:
    """(префикс, суффикс) для единицы. Незнакомая единица возвращается как есть
    суффиксом — честнее, чем прятать её: увидим на витрине и добавим в словарь."""
    if not unit:
        return "", ""
    known = _UNITS.get(unit.strip())
    if known:
        return known
    return "", f" {unit.strip()}"


def fmt(value, unit: str | None, decimals: int | None = None) -> str:
    """Готовая строка «$4,36 / барр.» — для прозы и для мест, где фронт не считает сам."""
    if value is None:
        return "—"
    pref, suf = parts(unit)
    try:
        num = float(value)
    except (TypeError, ValueError):
        return f"{pref}{value}{suf}"
    if decimals is None:
        decimals = 0 if abs(num) >= 100 else (1 if abs(num) >= 10 else 2)
    body = f"{num:,.{decimals}f}".replace(",", " ").replace(".", ",")
    return f"{pref}{body}{suf}"
