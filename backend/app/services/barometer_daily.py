# Служебные коды схемы в тексте, который видит пользователь. Правило в промпте не
# гарантирует ничего: модель охотно пишет «S3→S2» и «риск G7». Здесь ловим кодом и
# чистим — витрина не место для нашей нумерации (владелец, 2026-08-10).
# Предлог перед кодом забираем вместе с ним: иначе «риск по G7 вырос» превращается
# в «риск по вырос» — вычистили код, а фразу сломали.
# 🔴 Суффиксы обязательны: на бою осталось «S3→S4a: официальное объявление
# мобилизации» — шаблон \b[SG]\d{1,2}\b не срабатывал, потому что после цифры шла
# буква и границы слова не было. Ловим S4a/S4b/G7a и цепочки переходов целиком,
# вместе с двоеточием после них.
_CODE = r"(?:[SG]\d{1,2}[a-zа-я]?|ME\d[a-zа-я]?|ATR\d[a-zа-я]?)"
_CODES_RE = re.compile(
    r"(?:\s+(?:по|в|к|с|до|из|на|при)\s+)?"
    rf"\b{_CODE}(?:\s*[→>\-–]\s*{_CODE})*\b\s*:?\s*")
# Поля, которые читает человек. Ключи схемы (key) НЕ трогаем — это идентификаторы.
# 🔴 "trigger"/"impact"/"name"/"escalation_note" добавлены по факту проверки выдачи
# на бою: коды пережили чистку внутри scenario.wild_cards — это список СЛОВАРЕЙ, а
# перечень человеческих списков ждал список строк, и до вложенных полей чистка не
# доходила. Поле сейчас нигде не рисуется, но «не рисуется» — не защита: начнём
# рисовать, и G13 вылезет читателю.
_HUMAN_FIELDS = ("label", "summary", "rationale", "delta_rationale", "note",
                 "delta_explanation", "reasoning", "why", "expected_effect", "signal",
                 "trigger", "impact", "name", "escalation_note", "market_check")


# Ключи, под которыми лежат СПИСКИ СТРОК для человека. Их пропускала первая версия:
# рекурсия заходила в список, видела строки (не dict и не list) и молча выходила —
# поэтому «S3→S4a: официальное объявление мобилизации» в triggers доживало до витрины.
_HUMAN_LISTS = ("triggers", "wild_cards", "basis", "watchlist_30d", "affected")


def _clean_text(s: str) -> str:
    import re as _re
    out = _CODES_RE.sub("", s)
    out = _re.sub(r"\s{2,}", " ", out)
    out = _re.sub(r"\s+([,.;:)])", r"\1", out)
    # 🔴 Убрать мусор, оставшийся ОТ вырезания: перечисление кодов в скобках
    # («(G13, G1)») превращалось в «(,)» — читателю это выглядит как опечатка,
    # то есть чистка кодов создавала новый дефект вместо старого.
    out = _re.sub(r"\(\s*[,;\s]*\)", "", out)
    out = _re.sub(r",\s*,+", ",", out)
    # подряд идущие знаки после вырезания («переход,; рост») схлопываем в последний
    out = _re.sub(r"[,;:]\s*(?=[,;:])", "", out)
    out = _re.sub(r"\s{2,}", " ", out)
    return out.strip(" ,;:-–—")


def _strip_codes(obj, notes: list[str], path: str = "") -> None:
    """Вырезать служебные коды из человекочитаемых полей, рекурсивно."""
    if isinstance(obj, dict):
        for k, v in obj.items():
            if isinstance(v, str) and k in _HUMAN_FIELDS and _CODES_RE.search(v):
                obj[k] = _clean_text(v)
                notes.append(f"{path}{k}: убраны служебные коды")
            elif isinstance(v, list) and k in _HUMAN_LISTS:
                for i, item in enumerate(v):
                    if isinstance(item, str) and _CODES_RE.search(item):
                        v[i] = _clean_text(item)
                        notes.append(f"{path}{k}[{i}]: убраны служебные коды")
                    else:
                        _strip_codes(item, notes, f"{path}{k}.{i}.")
            else:
                _strip_codes(v, notes, f"{path}{k}.")
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            _strip_codes(v, notes, f"{path}{i}.")


def _drop_scores(payload: dict) -> None:
    """Убрать числовые баллы остроты — и общий, и по очагам.

    Оставляем label и escalation_note: словесный вердикт и условие роста влияния
    полезны, а число обещало точность, которой за ним не стояло.
    """
    for holder in ((payload.get("barometer") or {}),):
        for k in ("overall", "score", "escalation_potential"):
            holder.pop(k, None)
    for r in (payload.get("regions") or {}).values():
        if isinstance(r, dict) and isinstance(r.get("barometer"), dict):
            for k in ("overall", "score", "escalation_potential"):
                r["barometer"].pop(k, None)


# Обязательные подполя блоков. Появилось новое поле в спецификации — допиши его
# сюда, иначе блок будет копироваться из вчерашнего в старой форме бесконечно.
_SHAPE_REQUIRED = {
    "institutional_chain": ("layer", "winners", "losers"),
    "macro_chain": ("channel", "order", "reversibility"),
}


def _drop_stale_shape(prev: dict) -> tuple[dict, list[str]]:
    """Убрать из «вчерашнего» блоки, собранные по устаревшей форме.

    Возвращает (очищенная копия, список того, что удалено). Проверяем по ПЕРВОМУ
    элементу списка: если у него нет ни одного из обязательных новых подполей —
    блок старый целиком. Частично заполненные не трогаем: там модель уже перешла
    на новую форму, а отсутствие отдельного поля может быть законным «нечего
    сказать».
    """
    import copy
    out = copy.deepcopy(prev)
    dropped: list[str] = []
    for rkey, reg in (out.get("regions") or {}).items():
        if not isinstance(reg, dict):
            continue
        for field, required in _SHAPE_REQUIRED.items():
            items = reg.get(field)
            if not isinstance(items, list) or not items:
                continue
            first = items[0] if isinstance(items[0], dict) else {}
            if not any(first.get(k) for k in required):
                reg.pop(field, None)
                dropped.append(f"{rkey}.{field}")
    if dropped:
        logger.info("barometer_daily: удалены блоки устаревшей формы: %s",
                    ", ".join(dropped))
    return out, dropped


def _gate(fresh: dict, prev: dict) -> tuple[dict, list[str]]:
    """Возвращает (выпуск, заметки). НЕ отклоняет весь прогон из-за одного балла:
    сдвиг без обоснования просто откатывается к вчерашнему значению — так суточная
    пересборка не срывается целиком из-за одной небрежной строки.
    Комплаенс — отдельно и жёстко (см. compliance_ok), там fail-closed."""
    notes: list[str] = []
    _strip_codes(fresh, notes)
    prev_idx = _index_subindices(prev)
    for s in fresh.get("subindices") or []:
        key = s.get("key")
        p = prev_idx.get(key)
        if not p:
            continue
        try:
            new_score, old_score = float(s.get("score")), float(p.get("score"))
        except (TypeError, ValueError):
            s["score"] = p.get("score")
            notes.append(f"{key}: нечисловой балл → откат")
            continue
        if abs(new_score - old_score) < 1e-9:
            continue
        just = (s.get("delta_rationale") or "").strip()
        if len(just) < 20:                       # пусто/отписка «уточнено»
            s["score"] = old_score
            s["delta_rationale"] = None
            notes.append(f"{key}: {old_score}→{new_score} без обоснования → откат")

    # вероятности сценариев: нормализуем к 1.0, чтобы витрина не показывала 97%/103%
    sc = fresh.get("scenario") or {}
    for hk in ("probabilities_6m", "probabilities_18m"):
        probs = sc.get(hk)
        if isinstance(probs, dict) and probs:
            try:
                total = sum(float(v) for v in probs.values())
                if total > 0 and abs(total - 1.0) > 0.005:
                    sc[hk] = {k: round(float(v) / total, 3) for k, v in probs.items()}
                    notes.append(f"{hk}: сумма {total:.3f} → нормализована")
            except (TypeError, ValueError):
                notes.append(f"{hk}: нечисловые вероятности — оставлены как есть")

    # то же для сценариев КАЖДОГО очага (владелец 2026-08-01: сценарии должны быть
    # по очагам, а не общие) — суммы считаются внутри очага независимо.
    for rkey, r in (fresh.get("regions") or {}).items():
        items = ((r or {}).get("scenarios") or {}).get("items")
        if not isinstance(items, list) or not items:
            continue
        for field in ("p6m", "p18m"):
            try:
                vals = [float(it.get(field)) for it in items if it.get(field) is not None]
                total = sum(vals)
            except (TypeError, ValueError):
                notes.append(f"{rkey}.{field}: нечисловые вероятности — как есть")
                continue
            if total > 0 and abs(total - 1.0) > 0.005:
                for it in items:
                    if it.get(field) is not None:
                        it[field] = round(float(it[field]) / total, 3)
                notes.append(f"{rkey}.{field}: сумма {total:.3f} → нормализована")
    return fresh, notes


