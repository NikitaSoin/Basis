/**
 * Гостевой доступ: собрать портфель и спросить ассистента можно без регистрации.
 *
 * Владелец 2026-08-04: «клиент может зайти и потыкаться, просто у него портфель не
 * сохранится… и нужно, чтобы портфель, который он составил, сохранился после того как
 * пройдёт регистрацию, чтобы не слетело».
 *
 * Токен генерирует браузер и хранит у себя. Сервер по нему только находит портфель или
 * диалог — ни почты, ни имени, ни IP с ним не связано (см. backend/app/api/portfolios.py).
 *
 * 🔴 Токен НЕ заменяет авторизацию. Он живёт в localStorage, то есть теряется при очистке
 * данных браузера и не переносится на другое устройство. Это и есть причина, по которой
 * гостю честно говорят: хотите сохранить — зарегистрируйтесь.
 */
const KEY = "basis_guest_token";

/** Стабильный идентификатор гостя. Создаётся при первом обращении. */
export function getGuestToken() {
  try {
    let t = localStorage.getItem(KEY);
    // Бэкенд принимает только 16–64 буквенно-цифровых символа: короче — вероятно мусор
    // от старой версии или ручной правки, такой токен молча перевыпускаем.
    if (!t || !/^[a-zA-Z0-9]{16,64}$/.test(t)) {
      t = (crypto.randomUUID ? crypto.randomUUID() : `${Date.now()}${Math.random()}`)
        .replace(/[^a-zA-Z0-9]/g, "").slice(0, 32);
      localStorage.setItem(KEY, t);
    }
    return t;
  } catch {
    // Приватный режим/запрещённое хранилище: гостевой режим просто не работает,
    // но приложение не падает — пользователь увидит обычное предложение войти.
    return null;
  }
}

/**
 * Заголовки запроса: у зарегистрированного — токен доступа, у гостя — гостевой.
 * ОБА сразу не отправляем: на сервере владелец проверяется первым, и лишний заголовок
 * только запутывал бы отладку.
 */
export function apiHeaders(token, extra) {
  const h = { ...(extra || {}) };
  if (token) {
    h.Authorization = `Bearer ${token}`;
  } else {
    const g = getGuestToken();
    if (g) h["X-Guest-Token"] = g;
  }
  return h;
}

/**
 * Перенести гостевой портфель на аккаунт. Вызывается СРАЗУ после успешного входа или
 * регистрации — до того, как экран начнёт грузить список портфелей, иначе пользователь
 * увидит пустой список и решит, что работа пропала.
 */
export async function claimGuestData(apiUrl, token) {
  const g = getGuestToken();
  if (!g || !token) return null;
  try {
    const r = await fetch(`${apiUrl}/api/portfolios/claim`, {
      method: "POST",
      headers: { Authorization: `Bearer ${token}`, "X-Guest-Token": g, "Content-Type": "application/json" },
    });
    if (!r.ok) return null;
    const claimed = await r.json();
    // Токен после переноса больше не нужен: портфель теперь принадлежит аккаунту, а
    // оставленный токен на общем компьютере дал бы доступ следующему гостю.
    if (Array.isArray(claimed) && claimed.length) {
      try { localStorage.removeItem(KEY); } catch { /* хранилище недоступно — не критично */ }
    }
    return claimed;
  } catch {
    return null;  // сеть подвела — портфель не потерян, перенос повторится при следующем входе
  }
}
