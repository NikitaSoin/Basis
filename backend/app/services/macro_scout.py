"""Разведка перед макро-выпуском: добрать то, чего нет в наших рядах.

🔴 ЗАЧЕМ ИМЕННО ЗДЕСЬ. Сквозная боль платформы — устаревшие входные данные:
Росстат машинно недоступен, часть фидов отстаёт, отдельные ряды прекращены. До
сих пор интерпретатор работал ровно с тем, что лежало в снапшоте: не было
свежего значения — он либо молчал, либо писал общими словами. Пойти и проверить,
вышла ли публикация, было нечем.

Теперь перед выпуском идёт разведка: агент смотрит на снапшот, находит места,
где данные СТАРЫЕ или отсутствуют, и добирает их из первоисточника — сайта
регулятора, релиза, календаря публикаций. Всё найденное попадает в досье с
источником, а чего добыть не удалось — в список пробелов.

🔴 ЧЕГО РАЗВЕДКА НЕ ДЕЛАЕТ. Не пишет числа в базу показателей. Это сознательно:
на этом проекте уже был случай, когда добытчик показателей давал невоспроизводимые
между прогонами значения, и его пришлось оставить в сухом режиме. Досье — материал
для ТЕКСТА выпуска с явной ссылкой на источник, а не молчаливая правка рядов.
Ряд правится отдельным контуром со сверкой единиц и второго источника.
"""
from __future__ import annotations

import json
import logging
from datetime import date

from sqlalchemy.orm import Session

logger = logging.getLogger(__name__)

DOSSIER_KIND = "macdoss"   # колонка varchar(8) — имя обязано быть коротким

_SYS = (
    "Ты — аналитик-разведчик Basis по макроэкономике России. На этом шаге ты НЕ "
    "пишешь выпуск: ты собираешь материал для аналитика, который будет писать "
    "после тебя.\n\n"
    "Что от тебя нужно:\n"
    "1. Посмотреть переданный снапшот данных платформы и найти СЛАБЫЕ МЕСТА: где "
    "значение старое, где ряд оборван, где показателя нет вовсе, где две величины "
    "противоречат друг другу.\n"
    "2. Добрать это из первоисточника: сайт Банка России, Росстат, Минфин, "
    "релизы, календари публикаций, отчёты. Открывай документы и доставай числа "
    "оттуда, а не из пересказов.\n"
    "3. Там, где нужна ЛОГИКА (как связаны ставка, инфляция, курс, бюджет; через "
    "какой канал внешний шок доходит до показателя) — открыть нужный раздел "
    "методички и рассуждать по нему.\n"
    "4. Записать досье: числа с датой и источником отдельно, разбор отдельно, и "
    "честно — чего добыть не удалось.\n\n"
    "🔴 ЕДИНИЦЫ И ПЕРИОД — ЧАСТЬ ЧИСЛА. Всегда фиксируй, за какой период значение "
    "и в чём измерено (% год к году, % месяц к месяцу, млрд руб., пункты). Ряд "
    "врёт не только устареванием: под верным названием может лежать чужая метрика "
    "или другая единица. Если период или единица неясны — это ПРОБЕЛ, а не факт.\n"
    "🔴 СТРАНА ПОКАЗАТЕЛЯ ТОЖЕ ЧАСТЬ ЧИСЛА. Проверяй, что нашёл российский "
    "показатель, а не одноимённый чужой.\n"
    "🔴 Не предлагай изменений в базу данных — твой результат идёт в ТЕКСТ "
    "выпуска со ссылкой на источник.\n\n"
)


def _task(snapshot: dict, prev_summary: str = "") -> str:
    parts = [f"СЕГОДНЯ: {date.today().isoformat()}"]
    if prev_summary:
        parts.append("О ЧЁМ БЫЛ ПРОШЛЫЙ ВЫПУСК (чтобы искать ИЗМЕНЕНИЯ, а не "
                     "пересказывать):\n" + prev_summary[:1200])
    parts.append("СНАПШОТ ДАННЫХ ПЛАТФОРМЫ (это всё, что у нас есть; ищи в нём "
                 "устаревшее, оборванное и противоречивое):\n"
                 + json.dumps(snapshot, ensure_ascii=False)[:14000])
    parts.append(
        "ЗАДАЧА: собери досье под макро-выпуск. Что вышло нового по ключевым "
        "показателям (инфляция, ставка, курс, бюджет, кредит, рынок труда, "
        "деловая активность), с датой публикации и источником; какие наши "
        "значения устарели или расходятся с первоисточником; какие связи между "
        "показателями сейчас работают (рассуждай по методичке macro, при внешних "
        "шоках — по geo_macro). Чего не нашёл — в пробелы, честно.")
    return "\n\n".join(parts)


def run(db: Session, snapshot: dict, prev_summary: str = "",
        max_steps: int = 12, web_call_cap: int = 6) -> dict | None:
    from app.services import scout
    return scout.run(db, kind=DOSSIER_KIND, system=_SYS,
                     task=_task(snapshot, prev_summary),
                     shelf_docs=["macro", "geo_macro"],
                     max_steps=max_steps, web_call_cap=web_call_cap,
                     trigger_reason="разведка перед макро-выпуском")


def dossier_block(dossier: dict | None) -> str:
    from app.services.scout import dossier_block as _block
    return _block(dossier, title="СОБРАННОЕ ДОСЬЕ ПО МАКРОДАННЫМ")
