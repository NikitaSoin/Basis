def _release_text(sections: dict) -> str:
    """Текст выпуска для проверки: заголовок, тезисы с цепочками, событие, прогнозы."""
    parts: list[str] = []
    if sections.get("headline"):
        parts.append(f"ГЛАВНЫЙ ВЫВОД: {sections['headline']}")
    for t in sections.get("theses") or []:
        if not isinstance(t, dict):
            continue
        parts.append("ТЕЗИС [{}]: {}\n  цепочка: {}\n  данные: {}".format(
            t.get("tag") or "?", t.get("claim") or "", t.get("chain") or "",
            t.get("evidence") or ""))
    ev = sections.get("event_context")
    if isinstance(ev, dict) and ev.get("event"):
        parts.append(f"СОБЫТИЕ: {ev.get('event')}\n  эффект: {ev.get('macro_effect') or ''}")
    for f in sections.get("forecasts") or []:
        if isinstance(f, dict):
            parts.append("ПРОГНОЗ {}: {} ({}), драйвер: {}".format(
                f.get("variable"), f.get("center"), f.get("horizon"), f.get("driver")))
    for s in sections.get("sectors") or []:
        if isinstance(s, dict):
            parts.append(f"СЕКТОР {s.get('sector')}: {s.get('wind')} — {s.get('channel')}")
    return "\n\n".join(parts)[:12000]


def review_logic(db: Session, sections: dict) -> dict:
    """Проверить цепочки рассуждений. Возвращает замечания, ничего не переписывая."""
    text = _release_text(sections)
    if len(text) < 200:
        return {"issues": [], "verdict": "ok", "note": "нечего проверять"}
    user = (f"Сегодня {datetime.now(timezone.utc).date().isoformat()}. "
            f"Проверь логику этого макро-выпуска:\n\n{text}")
    try:
        out = llm.complete(_SYSTEM, user, json_mode=True, max_tokens=2000,
                           model=llm.pro_model())
    except Exception as e:  # noqa: BLE001
        logger.warning("logic-critic: прогон не удался: %s", type(e).__name__)
        return {"issues": [], "verdict": "unavailable", "error": type(e).__name__}
    issues = [i for i in (out.get("issues") or []) if isinstance(i, dict) and i.get("problem")]
    hard = [i for i in issues if i.get("severity") == "грубая"]
    if issues:
        logger.warning("logic-critic: замечаний %s (грубых %s): %s",
                       len(issues), len(hard), [i.get("problem", "")[:70] for i in issues[:4]])
    return {"issues": issues[:8], "hard_count": len(hard),
            "verdict": "исправить" if hard else (out.get("verdict") or "ok")}


def format_for_prompt(review: dict | None) -> str:
    """Замечания критика в текст для ПОВТОРНОЙ генерации выпуска."""
    issues = (review or {}).get("issues") or []
    if not issues:
        return ""
    lines = ["🔴 КРИТИК МАКРО-ЛОГИКИ нашёл ошибки в ПРЕДЫДУЩЕЙ версии этого выпуска. "
             "Не повторяй их:"]
    for i in issues:
        lines.append(f"- «{str(i.get('where'))[:110]}» — {i.get('problem')} "
                     f"Как правильно: {i.get('fix')}")
    return "\n".join(lines)
